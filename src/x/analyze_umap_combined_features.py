#!/usr/bin/env python3
"""
Combined UMAP coloured by Gaia parameter values.

Reads (generated by analyze_umap_query.py):
  output/umap/arrays/combined.npz             — embedding, categories, X_raw
  output/umap/arrays/combined_rebalanced.npz  — embedding, categories, X_raw

Writes:
  output/umap/combined/combined_features.png
  output/umap/combined/combined_features_rebalanced.png

Usage:
  python src/analyze_umap_combined_features.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
from matplotlib.gridspec import GridSpec

sys.path.insert(0, str(Path(__file__).parent))
from selected_parameters_list import SELECTED_GAIA_PARAMETERS

PROJECT_DIR = Path(__file__).resolve().parents[1]
ARRAYS_DIR  = PROJECT_DIR / "output" / "umap" / "arrays"
OUTPUT_DIR  = PROJECT_DIR / "output" / "umap" / "combined"

MAG_CUT = 17


def plot_combined_features(embedding, X_raw, categories, output_dir,
                           filename="combined_features.png",
                           xlim=None, ylim=None,
                           mag_label=None):
    """Grid of UMAP panels coloured by individual Gaia parameter values, combined Q1+ERO.

    Each feature occupies two stacked panels: upper = stars, lower = galaxies.
    ERO sources plotted as squares, Q1 as circles.
    Layout: 4 feature columns; rows determined by number of features.
    """
    n_features = len(SELECTED_GAIA_PARAMETERS)
    ncols = 4
    nfeature_rows = int(np.ceil(n_features / ncols))

    # categories: 0=Q1-STAR, 1=Q1-GALAXY, 2=ERO-STAR, 3=ERO-GALAXY
    is_ero    = categories >= 2
    is_star   = (categories == 0) | (categories == 2)
    is_galaxy = (categories == 1) | (categories == 3)

    per_panel_height = 1.2
    panel_h   = 1.0
    inner_gap = 0.04
    outer_gap = 0.32

    height_ratios = []
    for i in range(nfeature_rows):
        height_ratios.extend([panel_h, inner_gap, panel_h])
        if i < nfeature_rows - 1:
            height_ratios.append(outer_gap)

    panel_fraction = panel_h / sum(height_ratios)
    fig_width  = ncols * 3.8
    fig_height = per_panel_height / panel_fraction

    fig = plt.figure(figsize=(fig_width, fig_height))
    gs  = GridSpec(len(height_ratios), ncols,
                   figure=fig, height_ratios=height_ratios,
                   hspace=0, wspace=0.35)

    def _gs_top(feat_row): return feat_row * 4
    def _gs_bot(feat_row): return feat_row * 4 + 2

    for fi, feat_name in enumerate(SELECTED_GAIA_PARAMETERS):
        feat_row = fi // ncols
        col      = fi % ncols
        ax_top = fig.add_subplot(gs[_gs_top(feat_row), col])
        ax_bot = fig.add_subplot(gs[_gs_bot(feat_row), col])

        vals = X_raw[:, fi].astype(float)
        lo, hi = np.nanpercentile(vals, 2), np.nanpercentile(vals, 98)
        vals_clipped = np.clip(vals, lo, hi)

        for ax, class_mask, label in [
                (ax_top, is_star,   'Stars'),
                (ax_bot, is_galaxy, 'Galaxies')]:
            # grey background for all sources of this class (fills NaN holes)
            for ero_flag, marker in [(True, 's'), (False, 'o')]:
                bg_mask = class_mask & (is_ero == ero_flag)
                ax.scatter(
                    embedding[bg_mask, 0], embedding[bg_mask, 1],
                    c='lightgrey', s=4, alpha=0.18, marker=marker,
                    rasterized=True, linewidths=0, zorder=0,
                )
            # ERO squares first, Q1 circles on top (colored by feature)
            for ero_flag, marker in [(True, 's'), (False, 'o')]:
                mask = class_mask & (is_ero == ero_flag)
                sc = ax.scatter(
                    embedding[mask, 0], embedding[mask, 1],
                    c=vals_clipped[mask], cmap='RdYlBu_r',
                    vmin=lo, vmax=hi,
                    s=4, alpha=0.6, marker=marker, rasterized=True,
                    linewidths=0, zorder=1,
                )
            ax.set_xticks([]); ax.set_yticks([])
            ax.grid(alpha=0.25)
            if xlim is not None:
                ax.set_xlim(xlim)
            if ylim is not None:
                ax.set_ylim(ylim)
            ax.set_ylabel(f'{label}\n(n={class_mask.sum():,})', fontsize=7)

        fig.colorbar(sc, ax=[ax_top, ax_bot], pad=0.02, fraction=0.046).ax.tick_params(labelsize=7)
        ax_top.set_title(feat_name, fontsize=8, fontweight='bold', pad=4)

    for fi in range(n_features, nfeature_rows * ncols):
        feat_row = fi // ncols
        col      = fi % ncols
        fig.add_subplot(gs[_gs_top(feat_row), col]).set_visible(False)
        fig.add_subplot(gs[_gs_bot(feat_row), col]).set_visible(False)

    fig.suptitle(
        f"Combined UMAP coloured by Gaia parameters  ({mag_label if mag_label is not None else f'G \u2265 {MAG_CUT}'},  "
        f"{len(SELECTED_GAIA_PARAMETERS)} features)  |  Upper = stars, Lower = galaxies",
        fontsize=12, fontweight='bold', y=0.93,
    )
    out = output_dir / filename
    plt.savefig(out, dpi=150, bbox_inches='tight')
    plt.close()
    print(f"  -> Saved: {out}")


def main() -> int:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    indiv_path = ARRAYS_DIR / "combined.npz"
    rebal_path = ARRAYS_DIR / "combined_rebalanced.npz"

    if not indiv_path.exists():
        print(f"ERROR: missing file {indiv_path}")
        print("Run analyze_umap_query.py first to generate the saved arrays.")
        return 1

    print("Loading combined UMAP arrays...")
    data      = np.load(indiv_path, allow_pickle=True)
    mag_cut_faint = int(data['mag_cut_faint']) if 'mag_cut_faint' in data else 99
    mag_label = f'G \u2265 {MAG_CUT}' if mag_cut_faint >= 90 else f'{MAG_CUT} \u2264 G \u2264 {mag_cut_faint}'
    embedding  = data['embedding']
    categories = data['categories']
    X_raw      = data['X_raw']
    print(f"  embedding shape: {embedding.shape}  "
          f"(0=Q1-STAR, 1=Q1-GALAXY, 2=ERO-STAR, 3=ERO-GALAXY)")

    xlim = (embedding[:, 0].min() - 1.0, embedding[:, 0].max() + 1.0)
    ylim = (embedding[:, 1].min() - 1.0, embedding[:, 1].max() + 1.0)

    print("\nPlotting combined UMAP coloured by Gaia features...")
    plot_combined_features(embedding, X_raw, categories, OUTPUT_DIR,
                           xlim=xlim, ylim=ylim, mag_label=mag_label)

    if not rebal_path.exists():
        print(f"WARNING: {rebal_path} not found — skipping rebalanced features plot.")
        return 0

    print("\nLoading rebalanced combined arrays...")
    rebal_data      = np.load(rebal_path, allow_pickle=True)
    emb_rebal        = rebal_data['embedding']
    categories_rebal = rebal_data['categories']
    X_rebal          = rebal_data['X_raw']
    print(f"  Rebalanced: {(categories_rebal < 2).sum():,} Q1  "
          f"{(categories_rebal >= 2).sum():,} ERO")

    rebal_xlim = (emb_rebal[:, 0].min() - 1.0, emb_rebal[:, 0].max() + 1.0)
    rebal_ylim = (emb_rebal[:, 1].min() - 1.0, emb_rebal[:, 1].max() + 1.0)

    print("\nPlotting rebalanced combined UMAP coloured by Gaia features...")
    plot_combined_features(emb_rebal, X_rebal, categories_rebal, OUTPUT_DIR,
                           filename="combined_features_rebalanced.png",
                           xlim=rebal_xlim, ylim=rebal_ylim, mag_label=mag_label)

    print(f"\nAll outputs saved under: {OUTPUT_DIR}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
