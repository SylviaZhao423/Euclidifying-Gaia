def plot_ero_features(embedding, X_raw, y, output_dir,
                           filename="ero_features.png",
                           title_prefix="ERO Individual UMAP",
                           background_embedding=None,
                           background_y=None,
                           background_color="lightgrey",
                           scale_reference_X=None,
                           xlim=None, ylim=None,
                           mag_label=None):
    """Grid of UMAP panels coloured by individual Gaia parameter values, ERO-only.

    Each feature occupies two stacked panels: upper = ERO Stars, lower = ERO Galaxies.
    Layout: 4 feature columns; rows determined by number of features.
    Output: ero_features.png
    """
    n_features = len(SELECTED_GAIA_PARAMETERS)
    ncols = 4
    nfeature_rows = int(np.ceil(n_features / ncols))

    m_star = y == 0
    m_gal  = y == 1

    per_panel_height = 1.2
    panel_h   = 1.0
    inner_gap = 0.04
    outer_gap = 0.32

    height_ratios = []
    for i in range(nfeature_rows):
        height_ratios.extend([panel_h, inner_gap, panel_h])
        if i < nfeature_rows - 1:
            height_ratios.append(outer_gap)

    panel_fraction = panel_h / sum(height_ratios)
    fig_width  = ncols * 3.8
    fig_height = per_panel_height / panel_fraction

    from matplotlib.gridspec import GridSpec
    fig = plt.figure(figsize=(fig_width, fig_height))
    gs  = GridSpec(len(height_ratios), ncols,
                   figure=fig, height_ratios=height_ratios,
                   hspace=0, wspace=0.35)

    def _gs_top(feat_row): return feat_row * 4
    def _gs_bot(feat_row): return feat_row * 4 + 2

    for fi, feat_name in enumerate(SELECTED_GAIA_PARAMETERS):
        feat_row = fi // ncols
        col      = fi % ncols
        ax_top = fig.add_subplot(gs[_gs_top(feat_row), col])
        ax_bot = fig.add_subplot(gs[_gs_bot(feat_row), col])

        vals = X_raw[:, fi].astype(float)
        ref_vals = scale_reference_X[:, fi].astype(float) if scale_reference_X is not None else vals
        lo, hi = np.nanpercentile(ref_vals, 2), np.nanpercentile(ref_vals, 98)
        vals_clipped = np.clip(vals, lo, hi)

        for ax, mask, label in [
                (ax_top, m_star, "ERO Stars"),
                (ax_bot, m_gal,  "ERO Galaxies")]:
            if background_embedding is not None and background_y is not None:
                bg_mask = background_y == (0 if "Stars" in label else 1)
                if np.any(bg_mask):
                    ax.scatter(
                        background_embedding[bg_mask, 0],
                        background_embedding[bg_mask, 1],
                        c=background_color,
                        s=4, alpha=0.18, marker="s", rasterized=True,
                        linewidths=0, zorder=0,
                    )
            sc = ax.scatter(
                embedding[mask, 0], embedding[mask, 1],
                c=vals_clipped[mask], cmap="RdYlBu_r",
                vmin=lo, vmax=hi,
                s=4, alpha=0.6, marker="s", rasterized=True,
                linewidths=0, zorder=1,
            )
            ax.set_xticks([]); ax.set_yticks([])
            ax.grid(alpha=0.25)
            if xlim is not None:
                ax.set_xlim(xlim)
            if ylim is not None:
                ax.set_ylim(ylim)
            ax.set_ylabel(f"{label}\n(n={mask.sum():,})", fontsize=7)

        fig.colorbar(sc, ax=[ax_top, ax_bot], pad=0.02, fraction=0.046).ax.tick_params(labelsize=7)
        ax_top.set_title(feat_name, fontsize=8, fontweight="bold", pad=4)

    for fi in range(n_features, nfeature_rows * ncols):
        feat_row = fi // ncols
        col      = fi % ncols
        fig.add_subplot(gs[_gs_top(feat_row), col]).set_visible(False)
        fig.add_subplot(gs[_gs_bot(feat_row), col]).set_visible(False)

    fig.suptitle(
        f"{title_prefix} coloured by Gaia parameters  ({mag_label if mag_label is not None else f'G \u2265 {MAG_CUT}'},  {len(SELECTED_GAIA_PARAMETERS)} features)",
        fontsize=12, fontweight="bold", y=0.93,
    )
    out = output_dir / filename
    plt.savefig(out, dpi=150, bbox_inches="tight")
    plt.close()
    print(f"  -> Saved: {out}")


def assign_fields(ra: np.ndarray, dec: np.ndarray) -> np.ndarray:
    assignments = np.full(len(ra), None, dtype=object)
    min_dist = np.full(len(ra), np.inf)
    for name, (f_ra, f_dec, _) in ERO_FIELDS.items():
        ra1 = np.radians(ra)
        dec1 = np.radians(dec)
        ra2 = np.radians(f_ra)
        dec2 = np.radians(f_dec)
        a = (
            np.sin((dec2 - dec1) / 2) ** 2
            + np.cos(dec1) * np.cos(dec2) * np.sin((ra2 - ra1) / 2) ** 2
        )
        dist = np.degrees(2 * np.arcsin(np.sqrt(np.clip(a, 0, 1))))
        mask = dist < min_dist
        assignments[mask] = name
        min_dist[mask] = dist[mask]
    return assignments


def query_ra_dec(username: str):
    import psycopg2
    import pandas as pd

    conn = psycopg2.connect(host=WSDB_HOST, database=WSDB_DB, user=username)
    df = pd.read_sql_query(f"""
        SELECT g_source_id,
               e_v_alpha_j2000 AS ra,
               e_v_delta_j2000 AS dec
        FROM siwei_zhao_2025.crossmatch_ero_gaia_0_3
        WHERE e_v_class_star IS NOT NULL
          AND g_phot_g_mean_mag >= {MAG_CUT}
        ORDER BY g_source_id
    """, conn)
    conn.close()
    df["g_source_id"] = df["g_source_id"].astype(str)
    return df



