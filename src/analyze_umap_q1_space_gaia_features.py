#!/usr/bin/env python3
"""
Project 50k random Gaia sources into Q1 UMAP space and colour by their
Gaia feature values.

Uses the already-projected Gaia sources from xgb_gaia_projected.csv
(generated by analyze_umap_q1_space_gaia_xgb.py).  Star/galaxy split
comes from the XGBoost P(gal) threshold.

Each panel shows one Gaia feature with:
  Upper = Predicted stars  (P(gal) < 0.5)
  Lower = Predicted galaxies  (P(gal) >= 0.5)

Reads:
  output/umap/arrays/q1_indiv.npz
  output/umap/arrays/xgb_gaia_projected.csv

Writes:
  output/umap/q1_individual/q1_space_gaia_features.png

Usage:
  python src/analyze_umap_q1_space_gaia_features.py
  python src/analyze_umap_q1_space_gaia_features.py --hilat
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import matplotlib.pyplot as plt
from matplotlib.gridspec import GridSpec
import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).parent))
from selected_parameters_list import SELECTED_GAIA_PARAMETERS

PROJECT_DIR = Path(__file__).resolve().parents[1]
ARRAYS_DIR  = PROJECT_DIR / "output" / "umap" / "arrays"
OUTPUT_DIR  = PROJECT_DIR / "output" / "umap" / "q1_individual"

MAG_CUT    = 17
GAL_THRESH = 0.5
NCOLS      = 4


# ── Plot ──────────────────────────────────────────────────────────────────────

def plot_gaia_features(
    q1_emb:    np.ndarray,   # (N_q1, 2)
    gaia_emb:  np.ndarray,   # (N_gaia, 2) — projected into Q1 space
    gal_prob:  np.ndarray,   # XGBoost P(gal)
    feat_vals: dict[str, np.ndarray],
    output_dir: Path,
    filename:   str = "q1_space_gaia_features.png",
    xlim=None, ylim=None,
    hilat:      bool = False,
):
    features      = [f for f in SELECTED_GAIA_PARAMETERS if f in feat_vals
                     and np.isfinite(feat_vals[f]).any()]
    n_features    = len(features)
    ncols         = NCOLS
    nfeature_rows = int(np.ceil(n_features / ncols))

    per_panel_height = 1.2
    panel_h   = 1.0
    inner_gap = 0.04
    outer_gap = 0.32

    height_ratios = []
    for i in range(nfeature_rows):
        height_ratios.extend([panel_h, inner_gap, panel_h])
        if i < nfeature_rows - 1:
            height_ratios.append(outer_gap)

    panel_fraction = panel_h / sum(height_ratios)
    fig_width  = ncols * 3.8
    fig_height = per_panel_height / panel_fraction

    fig = plt.figure(figsize=(fig_width, fig_height))
    gs  = GridSpec(len(height_ratios), ncols,
                   figure=fig, height_ratios=height_ratios,
                   hspace=0, wspace=0.35)

    def _gs_top(feat_row): return feat_row * 4
    def _gs_bot(feat_row): return feat_row * 4 + 2

    m_star = gal_prob < GAL_THRESH
    m_gal  = gal_prob >= GAL_THRESH

    n_star = m_star.sum()
    n_gal  = m_gal.sum()

    for fi, feat_name in enumerate(features):
        feat_row = fi // ncols
        col      = fi % ncols
        ax_top = fig.add_subplot(gs[_gs_top(feat_row), col])
        ax_bot = fig.add_subplot(gs[_gs_bot(feat_row), col])

        vals   = feat_vals[feat_name].astype(float)
        finite = vals[np.isfinite(vals)]
        lo, hi = np.nanpercentile(finite, 1), np.nanpercentile(finite, 99)
        if lo == hi:
            lo, hi = finite.min(), finite.max()
        vals_clipped = np.clip(vals, lo, hi)

        for ax, mask, label, n in [
                (ax_top, m_star, "Pred. Stars",    n_star),
                (ax_bot, m_gal,  "Pred. Galaxies", n_gal)]:
            # Q1 grey background
            ax.scatter(
                q1_emb[:, 0], q1_emb[:, 1],
                c="lightgrey", s=2, alpha=0.15, marker="o",
                rasterized=True, linewidths=0, zorder=0,
            )
            # Gaia points coloured by feature
            valid = mask & np.isfinite(vals)
            sc = ax.scatter(
                gaia_emb[valid, 0], gaia_emb[valid, 1],
                c=vals_clipped[valid], cmap="RdYlBu_r",
                vmin=lo, vmax=hi,
                s=6, alpha=0.7, marker="o", rasterized=True,
                linewidths=0, zorder=1,
            )
            ax.set_xticks([]); ax.set_yticks([])
            ax.grid(alpha=0.25)
            if xlim is not None: ax.set_xlim(xlim)
            if ylim is not None: ax.set_ylim(ylim)
            ax.set_ylabel(f"{label}\n(n={n:,})", fontsize=7)

        fig.colorbar(sc, ax=[ax_top, ax_bot],
                     pad=0.02, fraction=0.046).ax.tick_params(labelsize=7)
        ax_top.set_title(feat_name, fontsize=8, fontweight="bold", pad=4)

    # hide empty panels
    for fi in range(n_features, nfeature_rows * ncols):
        feat_row = fi // ncols
        col      = fi % ncols
        fig.add_subplot(gs[_gs_top(feat_row), col]).set_visible(False)
        fig.add_subplot(gs[_gs_bot(feat_row), col]).set_visible(False)

    subset_label = "High-latitude Gaia" if hilat else "Random Gaia"
    fig.suptitle(
        f"{subset_label} sources in Q1 UMAP space coloured by Gaia features  "
        f"(G ≥ {MAG_CUT}, {n_features} features)\n"
        f"Upper = predicted stars (P(gal) < {GAL_THRESH})  ·  "
        f"Lower = predicted galaxies (P(gal) ≥ {GAL_THRESH})",
        fontsize=11, fontweight="bold", y=0.93,
    )
    out = output_dir / filename
    plt.savefig(out, dpi=150, bbox_inches="tight")
    plt.close()
    print(f"  -> Saved: {out}")


# ── Main ──────────────────────────────────────────────────────────────────────

def main() -> int:
    parser = argparse.ArgumentParser(
        description="Plot Gaia features of projected Gaia sources in Q1 UMAP space"
    )
    parser.add_argument("--hilat", action="store_true",
                        help="Use high-latitude subset (xgb_gaia_hilat_projected.csv).")
    args = parser.parse_args()

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    # ── 1. Load Q1 embedding ─────────────────────────────────────────────────
    print("[1] Loading Q1 UMAP embedding...")
    q1      = np.load(ARRAYS_DIR / "q1_indiv.npz", allow_pickle=True)
    q1_emb  = q1["embedding"]
    print(f"  Q1: {len(q1_emb):,} sources")

    # ── 2. Load projected Gaia sources ───────────────────────────────────────
    if args.hilat:
        csv_path = ARRAYS_DIR / "xgb_gaia_hilat_projected.csv"
    else:
        csv_path = ARRAYS_DIR / "xgb_gaia_projected.csv"

    if not csv_path.exists():
        print(f"ERROR: {csv_path} not found.")
        print("Run analyze_umap_q1_space_gaia_xgb.py first.")
        return 1

    print(f"\n[2] Loading projected Gaia sources from {csv_path.name}...")
    df = pd.read_csv(csv_path)
    print(f"  {len(df):,} sources")

    gaia_emb  = df[["umap1", "umap2"]].values
    gal_prob  = df["gal_prob"].values

    n_star = (gal_prob < GAL_THRESH).sum()
    n_gal  = (gal_prob >= GAL_THRESH).sum()
    print(f"  Predicted stars: {n_star:,}  |  Predicted galaxies: {n_gal:,}")

    # ── 3. Extract feature values ────────────────────────────────────────────
    print("\n[3] Extracting Gaia feature values...")
    feat_vals: dict[str, np.ndarray] = {}
    for col in SELECTED_GAIA_PARAMETERS:
        if col not in df.columns:
            print(f"    {col:<35}  (not in CSV — skipped)")
            continue
        arr = pd.to_numeric(df[col], errors="coerce").values
        n_finite = np.isfinite(arr).sum()
        if n_finite > 0:
            feat_vals[col] = arr
            print(f"    {col:<35} {n_finite:>8,} finite values")
        else:
            print(f"    {col:<35}  (all NaN — skipped)")

    # ── 4. Compute shared axis limits ────────────────────────────────────────
    x_all = np.concatenate([q1_emb[:, 0], gaia_emb[:, 0]])
    y_all = np.concatenate([q1_emb[:, 1], gaia_emb[:, 1]])
    xlim  = (x_all.min() - 1.0, x_all.max() + 1.0)
    ylim  = (y_all.min() - 1.0, y_all.max() + 1.0)

    # ── 5. Plot ──────────────────────────────────────────────────────────────
    suffix = "_hilat" if args.hilat else ""
    print(f"\n[4] Plotting Gaia features in Q1 UMAP space...")
    plot_gaia_features(
        q1_emb, gaia_emb, gal_prob, feat_vals, OUTPUT_DIR,
        filename=f"q1_space_gaia_features{suffix}.png",
        xlim=xlim, ylim=ylim,
        hilat=args.hilat,
    )

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
