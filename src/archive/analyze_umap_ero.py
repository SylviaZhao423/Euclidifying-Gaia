#!/usr/bin/env python3
"""
ERO individual UMAP analysis.

Loads pre-computed arrays from output/umap/arrays/, plots the 3-row × 3-col
agreement figure, feature maps, and rebalanced ERO individual variants.
No DB connection required.

Reads (generated by analyze_umap.py):
  output/umap/arrays/ero_indiv.npz   — embedding, y, source_ids, X_raw
  output/umap/arrays/ero_desi.npz    — X_features, spectype, cat_value
  output/q1_to_ero/agree_both_star.csv
  output/q1_to_ero/agree_both_galaxy.csv
  output/q1_to_ero/disagree_ero_star_q1_gal.csv
  output/q1_to_ero/disagree_ero_gal_q1_star.csv

Writes:
  output/umap/ero_individual/ero_compare.png
  output/umap/ero_individual/ero_features.png
  output/umap/ero_individual/ero_umap.png
  output/umap/ero_individual/ero_compare_rebalanced.png
  output/umap/ero_individual/ero_features_rebalanced.png

Usage:
  python src/analyze_umap_ero.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).parent))
from selected_parameters_list import SELECTED_GAIA_PARAMETERS
