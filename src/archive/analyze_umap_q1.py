#!/usr/bin/env python3
"""
Standalone Q1 individual UMAP + DESI galaxy overlay plot.

Loads pre-computed arrays saved by analyze_umap.py, then plots a 2-row × 3-col
scatter + density figure with DESI galaxies projected onto the Q1 UMAP space.

Reads (generated by analyze_umap.py):
  output/umap/arrays/q1_indiv.npz           — embedding, y, source_ids, X_raw, mean, std
  output/umap/arrays/q1_reducer.joblib — fitted UMAP reducer for projection
  output/umap/arrays/q1_desi.npz            — X_features, spectype, cat_value

Writes:
  output/umap/q1_individual/q1_compare.png
  output/umap/q1_individual/q1_features.png

Usage:
  python src/analyze_umap_q1.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import joblib
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).parent))
from selected_parameters_list import SELECTED_GAIA_PARAMETERS

PROJECT_DIR = Path(__file__).resolve().parents[1]
ARRAYS_DIR  = PROJECT_DIR / "output" / "umap" / "arrays"
OUTPUT_DIR  = PROJECT_DIR / "output" / "umap" / "q1_individual"

MAG_CUT = 17


def plot_q1_individual_agreement(embedding_q1, y_q1,
                                  output_dir,
                                  max_points_per_group=15000,
                                  filename="q1_compare.png",
                                  desi_emb_star=None,
                                  desi_emb_gal=None):
    """1-row × 3-col plot of Q1 individual UMAP with DESI galaxy overlay."""
    rng = np.random.RandomState(0)

    x_all, y_all_emb = embedding_q1[:, 0], embedding_q1[:, 1]
    x_mid = (x_all.min() + x_all.max()) / 2
    y_mid = (y_all_emb.min() + y_all_emb.max()) / 2
    half = max(x_all.max() - x_all.min(), y_all_emb.max() - y_all_emb.min()) / 2 * 1.03
    x_lo, x_hi = x_mid - half, x_mid + half
    y_lo, y_hi = y_mid - half, y_mid + half

    m_star = y_q1 == 0
    m_gal  = y_q1 == 1

    def _sub(mask):
        idx = np.where(mask)[0]
        if len(idx) > max_points_per_group:
            idx = rng.choice(idx, max_points_per_group, replace=False)
        return idx

    def _style(ax, title):
        ax.set_xlim(x_lo, x_hi)
        ax.set_ylim(y_lo, y_hi)
        ax.set_aspect("equal", adjustable="box")
        ax.set_xlabel("UMAP 1", fontsize=10)
        ax.set_ylabel("UMAP 2", fontsize=10)
        ax.set_title(title, fontsize=11, fontweight="bold")
        ax.tick_params(labelsize=8)
        ax.grid(alpha=0.25)
        handles, labels = ax.get_legend_handles_labels()
        if handles:
            ax.legend(fontsize=8, loc="upper right", markerscale=1.5)

    from matplotlib.colors import LogNorm
    n_bins  = 200
    x_edges = np.linspace(x_lo, x_hi, n_bins + 1)
    y_edges = np.linspace(y_lo, y_hi, n_bins + 1)
    cmap_dens = plt.cm.Blues.copy()
    cmap_dens.set_bad(alpha=0)

    fig, axes = plt.subplots(2, 3, figsize=(18, 12), constrained_layout=True)

    # ── Row 1: scatter ────────────────────────────────────────────────────────
    for mask, color, label in [(m_star, "#1976D2", "STAR"), (m_gal, "#E53935", "GALAXY")]:
        idx = _sub(mask)
        axes[0, 0].scatter(embedding_q1[idx, 0], embedding_q1[idx, 1],
                           c=color, s=6, alpha=0.25, linewidths=0,
                           label=f"{label} (n={mask.sum():,})")
    _style(axes[0, 0], "Q1 — individual UMAP")

    idx = _sub(m_star)
    axes[0, 1].scatter(embedding_q1[idx, 0], embedding_q1[idx, 1],
                       c="#1976D2", s=6, alpha=0.25, linewidths=0,
                       label=f"STAR (n={m_star.sum():,})")
    _style(axes[0, 1], "Q1 Stars")

    idx = _sub(m_gal)
    axes[0, 2].scatter(embedding_q1[idx, 0], embedding_q1[idx, 1],
                       c="#E53935", s=6, alpha=0.25, linewidths=0,
                       label=f"GALAXY (n={m_gal.sum():,})")
    _style(axes[0, 2], "Q1 Galaxies")

    # ── DESI galaxy overlay on row 1 ─────────────────────────────────────────
    desi_per_col = [
        [desi_emb_star, desi_emb_gal],
        [desi_emb_star],
        [desi_emb_gal],
    ]
    for ci, emb_list in enumerate(desi_per_col):
        ax = axes[0, ci]
        all_pts = [e for e in emb_list if e is not None and len(e) > 0]
        if not all_pts:
            continue
        combined = np.vstack(all_pts)
        ax.scatter(combined[:, 0], combined[:, 1],
                   c="#2196F3", marker="o", s=30, alpha=0.85,
                   linewidths=0.4, edgecolors="white", zorder=5,
                   label=f"DESI GALAXY (n={len(combined):,})")
        handles, labels = ax.get_legend_handles_labels()
        ax.legend(handles, labels, fontsize=8, loc="upper right", markerscale=1.5)

    # ── Row 2: 2D source density ──────────────────────────────────────────────
    density_panels = [
        (np.ones(len(embedding_q1), dtype=bool), "All Q1 — source density"),
        (m_star,                                  "Q1 Stars — source density"),
        (m_gal,                                   "Q1 Galaxies — source density"),
    ]
    for ci, (mask, title) in enumerate(density_panels):
        ax = axes[1, ci]
        H, _, _ = np.histogram2d(
            embedding_q1[mask, 0], embedding_q1[mask, 1],
            bins=[x_edges, y_edges],
        )
        H = np.where(H > 0, H, np.nan)
        sc = ax.pcolormesh(x_edges, y_edges, H.T,
                           cmap=cmap_dens, norm=LogNorm(), rasterized=True)
        ax.set_xlim(x_lo, x_hi)
        ax.set_ylim(y_lo, y_hi)
        ax.set_box_aspect(1)
        ax.set_xlabel("UMAP 1", fontsize=10)
        ax.set_ylabel("UMAP 2", fontsize=10)
        ax.set_title(title, fontsize=11, fontweight="bold")
        ax.tick_params(labelsize=8)
        ax.grid(alpha=0.25)
        fig.colorbar(sc, ax=ax, label="Count (log)", pad=0.02, fraction=0.046)

    fig.suptitle(
        f"Q1 Individual UMAP  (G ≥ {MAG_CUT},  {len(SELECTED_GAIA_PARAMETERS)} features)",
        fontsize=13, fontweight="bold",
    )
    out = output_dir / filename
    fig.savefig(out, dpi=150, bbox_inches="tight")
    plt.close(fig)
    print(f"  -> Saved: {out}")


def plot_q1_features(embedding, X_raw, y, output_dir,
                           filename="q1_features.png"):
    """Grid of UMAP panels coloured by individual Gaia parameter values, Q1-only."""
    n_features = len(SELECTED_GAIA_PARAMETERS)
    ncols = 4
    nfeature_rows = int(np.ceil(n_features / ncols))

    m_star = y == 0
    m_gal  = y == 1

    per_panel_height = 1.2
    panel_h   = 1.0
    inner_gap = 0.04
    outer_gap = 0.32

    height_ratios = []
    for i in range(nfeature_rows):
        height_ratios.extend([panel_h, inner_gap, panel_h])
        if i < nfeature_rows - 1:
            height_ratios.append(outer_gap)

    panel_fraction = panel_h / sum(height_ratios)
    fig_width  = ncols * 3.8
    fig_height = per_panel_height / panel_fraction

    from matplotlib.gridspec import GridSpec
    fig = plt.figure(figsize=(fig_width, fig_height))
    gs  = GridSpec(len(height_ratios), ncols,
                   figure=fig, height_ratios=height_ratios,
                   hspace=0, wspace=0.35)

    def _gs_top(feat_row): return feat_row * 4
    def _gs_bot(feat_row): return feat_row * 4 + 2

    for fi, feat_name in enumerate(SELECTED_GAIA_PARAMETERS):
        feat_row = fi // ncols
        col      = fi % ncols
        ax_top = fig.add_subplot(gs[_gs_top(feat_row), col])
        ax_bot = fig.add_subplot(gs[_gs_bot(feat_row), col])

        vals = X_raw[:, fi].astype(float)
        lo, hi = np.nanpercentile(vals, 2), np.nanpercentile(vals, 98)
        vals_clipped = np.clip(vals, lo, hi)

        for ax, mask, label in [
                (ax_top, m_star, "Q1 Stars"),
                (ax_bot, m_gal,  "Q1 Galaxies")]:
            sc = ax.scatter(
                embedding[mask, 0], embedding[mask, 1],
                c=vals_clipped[mask], cmap="RdYlBu_r",
                vmin=lo, vmax=hi,
                s=4, alpha=0.6, marker="o", rasterized=True,
                linewidths=0,
            )
            ax.set_xticks([]); ax.set_yticks([])
            ax.grid(alpha=0.25)
            ax.set_ylabel(f"{label}\n(n={mask.sum():,})", fontsize=7)

        fig.colorbar(sc, ax=[ax_top, ax_bot], pad=0.02, fraction=0.046).ax.tick_params(labelsize=7)
        ax_top.set_title(feat_name, fontsize=8, fontweight="bold", pad=4)

    for fi in range(n_features, nfeature_rows * ncols):
        feat_row = fi // ncols
        col      = fi % ncols
        fig.add_subplot(gs[_gs_top(feat_row), col]).set_visible(False)
        fig.add_subplot(gs[_gs_bot(feat_row), col]).set_visible(False)

    fig.suptitle(
        f"Q1 Individual UMAP coloured by Gaia parameters  (G ≥ {MAG_CUT},  {len(SELECTED_GAIA_PARAMETERS)} features)  |  Upper = stars, Lower = galaxies",
        fontsize=12, fontweight="bold", y=0.93,
    )
    out = output_dir / filename
    plt.savefig(out, dpi=150, bbox_inches="tight")
    plt.close()
    print(f"  -> Saved: {out}")


def main() -> int:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    indiv_path   = ARRAYS_DIR / "q1_indiv.npz"
    reducer_path = ARRAYS_DIR / "q1_indiv_reducer.joblib"
    desi_path    = ARRAYS_DIR / "q1_desi.npz"

    for p in (indiv_path, reducer_path, desi_path):
        if not p.exists():
            print(f"ERROR: missing file {p}")
            print("Run analyze_umap.py first to generate the saved arrays.")
            return 1

    print("Loading Q1 individual UMAP arrays...")
    data = np.load(indiv_path, allow_pickle=True)
    embedding  = data['embedding']
    y          = data['y']
    source_ids = data['source_ids']
    X_raw      = data['X_raw']
    mean_      = data['mean']
    std_       = data['std']
    print(f"  embedding shape: {embedding.shape}  (0=STAR, 1=GALAXY)")

    print("Loading Q1 individual UMAP reducer...")
    reducer = joblib.load(reducer_path)

    print("Loading Q1 DESI features...")
    desi_data = np.load(desi_path, allow_pickle=True)
    gal_mask  = desi_data['spectype'] == 'GALAXY'
    desi_X    = desi_data['X_features'][gal_mask]
    desi_cat  = desi_data['cat_value'][gal_mask]

    def _project(X_subset):
        if len(X_subset) == 0:
            return None
        X_d = X_subset.astype(float)
        for c in range(X_d.shape[1]):
            bad = np.isnan(X_d[:, c])
            if bad.any():
                X_d[bad, c] = np.nanmedian(X_d[:, c])
        return reducer.transform((X_d - mean_) / np.where(std_ > 0, std_, 1.0))

    desi_emb_star = _project(desi_X[desi_cat == 0])
    desi_emb_gal  = _project(desi_X[desi_cat == 1])
    print(f"  Projected DESI Q1 galaxies: {(desi_cat==0).sum():,} Q1-star, {(desi_cat==1).sum():,} Q1-gal")

    print("\nPlotting Q1 individual UMAP with DESI overlay...")
    plot_q1_individual_agreement(embedding, y, OUTPUT_DIR,
                                  desi_emb_star=desi_emb_star,
                                  desi_emb_gal=desi_emb_gal)

    print("\nPlotting Q1 UMAP coloured by Gaia features...")
    plot_q1_features(embedding, X_raw, y, OUTPUT_DIR)

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
